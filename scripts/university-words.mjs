// Writes chinalife-api/university-words.php: the Chinese course words (public/chinese-course.js) for server-graded
// university exams. Run after changing the course: node scripts/university-words.mjs (tests/university-years.mjs
// fails while the two lists differ).
import fs from 'node:fs';import vm from 'node:vm';
const ctx={window:{}};vm.createContext(ctx);vm.runInContext(fs.readFileSync('public/chinese-course.js','utf8'),ctx);
const q=s=>"'"+String(s).replace(/\\/g,'\\\\').replace(/'/g,"\\'")+"'";
const rows=ctx.window.ChinaLifeChinese.allWords.map(w=>'['+[q(w.han),q(w.pin),q(w.en),w.unit].join(',')+']');
fs.writeFileSync('chinalife-api/university-words.php',"<?php\ndeclare(strict_types=1);\n// Generated by scripts/university-words.mjs from public/chinese-course.js: [characters, pinyin, English, unit index].\nfunction cl_uni_words(): array {return ["+rows.join(',')+"];}\n");
console.log('Wrote '+rows.length+' words');
